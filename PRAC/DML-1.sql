(
  SELECT UPPER(APELLIDO1)
  FROM PROFESORES
  WHERE APELLIDO1 IS NOT NULL
  UNION
  SELECT UPPER(APELLIDO2)
  FROM PROFESORES
  WHERE APELLIDO2 IS NOT NULL
);
(
  SELECT UPPER(APELLIDO1)
  FROM ALUMNOS
  WHERE APELLIDO1 IS NOT NULL
    AND UPPER(APELLIDO1) LIKE '%LL%'
  UNION
  SELECT UPPER(APELLIDO2)
  FROM ALUMNOS
  WHERE APELLIDO2 IS NOT NULL
    AND UPPER(APELLIDO2) LIKE '%LL%'
)
UNION
(
  SELECT UPPER(APELLIDO1)
  FROM PROFESORES
  WHERE APELLIDO1 IS NOT NULL
    AND UPPER(APELLIDO1) LIKE '%LL%'
  UNION
  SELECT UPPER(APELLIDO2)
  FROM PROFESORES
  WHERE APELLIDO2 IS NOT NULL
    AND UPPER(APELLIDO2) LIKE '%LL%'
