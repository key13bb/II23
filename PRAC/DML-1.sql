minus
select ASIGNATURA
from IMPARTIR;
SELECT EMAIL
FROM PROFESORES
WHERE EMAIL IS NOT NULL
UNION ALL
SELECT EMAIL
FROM ALUMNOS
WHERE EMAIL IS NOT NULL;
