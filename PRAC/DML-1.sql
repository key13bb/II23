(
  SELECT UPPER(REPLACE(APELLIDO1, 'LL', 'Y'))
  FROM ALUMNOS
  WHERE APELLIDO1 IS NOT NULL
    AND UPPER(APELLIDO1) LIKE '%LL%'
  UNION
  SELECT UPPER(REPLACE(APELLIDO2, 'LL', 'Y'))
  FROM ALUMNOS
  WHERE APELLIDO2 IS NOT NULL
    AND UPPER(APELLIDO2) LIKE '%LL%'
)
UNION
(
  SELECT UPPER(REPLACE(APELLIDO1, 'LL', 'Y'))
  FROM PROFESORES
  WHERE APELLIDO1 IS NOT NULL
    AND UPPER(APELLIDO1) LIKE '%LL%'
  UNION
  SELECT UPPER(REPLACE(APELLIDO2, 'LL', 'Y'))
  FROM PROFESORES
  WHERE APELLIDO2 IS NOT NULL
    AND UPPER(APELLIDO2) LIKE '%LL%'
);
/* Reuniones externas */
SELECT ASI.NOMBRE,
  PROFESOR
FROM ASIGNATURAS ASI
  LEFT OUTER JOIN IMPARTIR I ON ASI.CODIGO = I.ASIGNATURA
WHERE NVL(CREDITOS, 0) <> NVL(PRACTICOS, 0) + NVL(TEORICOS, 0);
SELECT P.NOMBRE || ' ' || P.APELLIDO1 || ' ' || P.APELLIDO2 "NOMBRE PROFESOR",
  D.NOMBRE || ' ' || D.APELLIDO1 || ' ' || D.APELLIDO2 "NOMBRE DIRECTOR"
FROM PROFESORES P
  LEFT OUTER JOIN PROFESORES D ON P.DIRECTOR_TESIS = D.ID
ORDER BY P.NOMBRE,
  P.APELLIDO1,
  P.APELLIDO2;
SELECT 'El director de ' || P.NOMBRE || ' ' || P.APELLIDO1 || ' ' || P.APELLIDO2 || ' es ' || D.NOMBRE || ' ' || D.APELLIDO1 || ' ' || D.APELLIDO2 "NOMBRE COMPLETO PROFESOR-DIRECTOR",
  NVL(I.TRAMOS, 0) "TRAMOS"
FROM PROFESORES P
  JOIN PROFESORES D ON (P.DIRECTOR_TESIS = D.ID)
  LEFT OUTER JOIN INVESTIGADORES I ON (D.ID = I.ID_PROFESOR);
SELECT A1.NOMBRE || ' ' || A1.APELLIDO1 || ' ' || A1.APELLIDO2 "NOMBRE DEL ALUMNO 1",
  A2.NOMBRE || ' ' || A2.APELLIDO1 || ' ' || A2.APELLIDO2 "NOMBRE DE ALUMNO 2:"
FROM ALUMNOS A1
  LEFT OUTER JOIN ALUMNOS A2 ON (
    A1.FECHA_PRIM_MATRICULA = A2.FECHA_PRIM_MATRICULA
    AND A1.DNI < A2.DNI
  )
ORDER BY A1.NOMBRE,
  A1.APELLIDO1,
  A1.APELLIDO2;
SELECT A.NOMBRE "NOMBRE ASIGNATURA",
  NVL(I.CURSO, ' ') "CURSO",
  NVL(I.GRUPO, ' ') "GRUPO",
  P.NOMBRE || ' ' || P.APELLIDO1 "NOMBRE PROFESOR"
FROM ASIGNATURAS A
  LEFT OUTER JOIN IMPARTIR I ON (A.CODIGO = I.ASIGNATURA)
  LEFT OUTER JOIN PROFESORES P ON (I.PROFESOR = P.ID);
/* Subconsultas */
SELECT NOMBRE,
  ID
FROM PROFESORES
WHERE ID NOT IN (
    SELECT PROFESOR
    FROM IMPARTIR
  );
SELECT NOMBRE || ' ' || APELLIDO1 || ' ' || APELLIDO2
FROM ALUMNOS
WHERE ROWNUM < 3
  AND UPPER(GENERO) = 'FEM'
  AND DNI IN (
    SELECT ALUMNO
    FROM MATRICULAR
    WHERE ASIGNATURA = 115
  );
SELECT *
FROM PROFESORES
WHERE ID NOT IN (
    SELECT DIRECTOR_TESIS
    FROM PROFESORES
    WHERE DIRECTOR_TESIS IS NOT NULL
  );
SELECT NOMBRE,
  CODIGO
FROM ASIGNATURAS A
WHERE EXISTS (
    SELECT *
    FROM ASIGNATURAS
    WHERE NVL(CREDITOS, 0) > NVL(A.CREDITOS, 0)
      AND NVL(CURSO, 0) = NVL(A.CURSO, 0)
  );
(
  SELECT NOMBRE,
    CODIGO
  FROM ASIGNATURAS
)
MINUS
(
  SELECT NOMBRE,
    CODIGO
  FROM ASIGNATURAS A
  WHERE EXISTS(
      SELECT *
      FROM ASIGNATURAS
      WHERE NVL(CREDITOS, 0) > NVL(A.CREDITOS, 0)
        AND NVL(CURSO, 0) = NVL(A.CURSO, 0)
    )
)